import { expect, test } from '@playwright/test'
import { authenticate, baseUrl, setPreviewRoute } from './color-picker-acceptance.helpers'

test.skip(process.env.COMPOSE_E2E !== '1', 'Requires the canonical Compose stack')
test.beforeEach(async ({ page }) => {
  await authenticate(page)
  await page.evaluate(() => localStorage.clear())
  await page.goto(baseUrl)
  await page.setViewportSize({ width: 1280, height: 900 })
})

test('theme dropdown and popover use friendly names, live mode colors and swatches', async ({ page }) => {
  await page.getByLabel('Primary color text', { exact: true }).fill('#123456')
  const field = page.locator('[data-color-field="page-surface"]')
  const select = field.locator('select[data-user-token-select]')
  await expect(select).toBeVisible()
  await expect(select.locator('option[value="var(--ftb-palette-primary-500)"]')).toHaveText('primary 500')
  await page.locator('[data-user-token-name]').fill('secondary')
  await page.locator('[data-user-token-value]').fill('#aa5500')
  await page.locator('[data-user-token-create]').click()
  await expect(select.locator('option[value="user.color.secondary"]')).toHaveText('secondary')
  await select.selectOption('var(--ftb-palette-primary-500)')
  const preview = page.frameLocator('iframe[title="Filament preview"]')
  await expect(preview.locator('body')).toHaveCSS('background-color', 'rgb(18, 52, 86)')
  await page.getByRole('button', { name: 'Dark mode', exact: true }).click()
  await page.getByLabel('Primary color text', { exact: true }).fill('#654321')
  await expect(preview.locator('body')).toHaveCSS('background-color', 'rgb(101, 67, 33)')
  await field.getByRole('button', { name: /Choose .* from Tailwind palette/ }).click()
  const dialog = page.getByRole('dialog', { name: 'page surface dark color choices', exact: true })
  await dialog.getByRole('tab', { name: 'Theme', exact: true }).click()
  await page.keyboard.press('Home')
  await expect(dialog.getByRole('tab', { name: 'Custom', exact: true })).toBeFocused()
  await page.keyboard.press('End')
  await expect(dialog.getByRole('tab', { name: 'Theme', exact: true })).toBeFocused()
  await expect(page.getByLabel('page surface dark', { exact: true })).toHaveValue('var(--ftb-palette-primary-500)')
  await expect(dialog.getByRole('button', { name: 'primary 500', exact: true }).locator('[data-theme-color-swatch]')).toHaveCSS('background-color', 'rgb(101, 67, 33)')
  await dialog.getByRole('button', { name: 'secondary', exact: true }).click()
  await expect(page.getByLabel('page surface dark', { exact: true })).toHaveValue('user.color.secondary')
  await expect(preview.locator('body')).toHaveCSS('background-color', 'rgb(170, 85, 0)')
})

test('semantic fields accept the same bounded built-in palette references', async ({ page }) => {
  await page.getByLabel('Primary color text', { exact: true }).fill('#123456')
  await setPreviewRoute(page, '/demo/admin/forms-showcase')
  await page.getByRole('tab', { name: 'Components', exact: true }).click()
  const field = page.locator('[data-color-field="product-name-global-background"]')
  await expect(field.locator('select[data-user-token-select]')).toBeVisible()
  await field.locator('select[data-user-token-select]').selectOption('var(--ftb-palette-primary-500)')
  const input = page.frameLocator('iframe[title="Filament preview"]').locator('.fi-fo-text-input .fi-input').first()
  await expect(input).toHaveCSS('background-color', 'rgb(18, 52, 86)')
  await page.getByLabel('Primary color text', { exact: true }).fill('#654321')
  await expect(input).toHaveCSS('background-color', 'rgb(101, 67, 33)')
})

test('an untouched palette shade applies the exact color advertised by its swatch', async ({ page }) => {
  const root = page.frameLocator('iframe[title="Filament preview"]').locator('html')
  const nativeBefore = await root.evaluate((node) => getComputedStyle(node).getPropertyValue('--primary-50'))
  const field = page.locator('[data-color-field="page-surface"]')
  await field.getByRole('button', { name: /Choose .* from Tailwind palette/ }).click()
  const dialog = page.getByRole('dialog', { name: 'page surface light color choices', exact: true })
  await dialog.getByRole('tab', { name: 'Theme', exact: true }).click()
  const choice = dialog.getByRole('button', { name: 'primary 50', exact: true })
  const advertised = await choice.locator('[data-theme-color-swatch]').evaluate((node) => getComputedStyle(node).backgroundColor)
  await choice.click()
  await expect(page.frameLocator('iframe[title="Filament preview"]').locator('body')).toHaveCSS('background-color', advertised)
  await expect.poll(() => root.evaluate((node) => getComputedStyle(node).getPropertyValue('--primary-50'))).toBe(nativeBefore)
})

test('empty inherited native picker is usable without applying on open or cancel', async ({ page }) => {
  await page.setViewportSize({ width: 1800, height: 1000 })
  const preview = page.frameLocator('iframe[title="Filament preview"]')
  const label = preview.locator('.fi-sidebar-item-label').first()
  await page.getByRole('button', { name: 'Inspector', exact: true }).click()
  await label.click()
  const field = page.locator('[data-color-field="raw-color"]')
  await expect(page.getByLabel('Raw color', { exact: true })).toHaveValue('')
  await field.getByRole('button', { name: 'Choose Raw color from Tailwind palette' }).click()
  const dialog = page.getByRole('dialog', { name: 'Raw color color choices', exact: true })
  await dialog.getByRole('tab', { name: 'Custom', exact: true }).click()
  const native = dialog.getByLabel('Raw color custom color picker', { exact: true })
  await expect(native).toBeEnabled()
  await page.setViewportSize({ width: 430, height: 820 })
  await expect(native).toBeVisible()
  await expect.poll(async () => { const box = await dialog.boundingBox(); return box !== null && box.x >= 0 && box.x + box.width <= 430 }).toBe(true)
  await page.setViewportSize({ width: 1800, height: 1000 })
  await page.keyboard.press('Escape')
  await expect(page.getByLabel('Raw color', { exact: true })).toHaveValue('')
  await field.getByRole('button', { name: 'Choose Raw color from Tailwind palette' }).click()
  await dialog.getByRole('tab', { name: 'Custom', exact: true }).click()
  await native.fill('#223344')
  await expect(label).toHaveCSS('color', 'rgb(34, 51, 68)')
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(page.getByLabel('Raw color', { exact: true })).toHaveValue('')
})

import { expect, test } from '@playwright/test'
import { authenticate, baseUrl } from './color-picker-acceptance.helpers'

test.skip(process.env.COMPOSE_E2E !== '1', 'Requires the canonical Compose stack')
test.beforeEach(async ({ page }) => {
  await authenticate(page)
  await page.evaluate(() => localStorage.clear())
  await page.goto(baseUrl)
  await page.setViewportSize({ width: 1800, height: 1200 })
})

test('generic table column targets cover headers and body without field-specific selectors', async ({ page }) => {
  const frame = page.frameLocator('iframe[title="Filament preview"]')
  const header = frame.locator('.fi-ta-header-cell').nth(1)
  await expect(header).toBeVisible()
  await page.getByRole('button', { name: 'Inspector', exact: true }).click()
  await header.click()
  await expect(page.getByLabel('Raw element selector')).toHaveValue('.fi-ta-header-cell')
  await page.getByLabel('Inspector target scope').selectOption({ label: 'Column 2 — header and body' })
  await expect(frame.locator('.ftb-inspector-selected.fi-ta-header-cell')).toHaveCount(await frame.locator('.fi-ta-header-cell:nth-child(2)').count())
  await expect(frame.locator('.ftb-inspector-selected.fi-ta-cell')).toHaveCount(await frame.locator('.fi-ta-cell:nth-child(2)').count())
  await page.getByLabel('Raw background-color', { exact: true }).fill('#123456')
  await expect(header).toHaveCSS('background-color', 'rgb(18, 52, 86)')
  const cells = frame.locator('.fi-ta-cell:nth-child(2)')
  for (let index = 0; index < await cells.count(); index++) await expect(cells.nth(index)).toHaveCSS('background-color', 'rgb(18, 52, 86)')
  await expect(frame.locator('.fi-ta-cell:nth-child(1)').first()).not.toHaveCSS('background-color', 'rgb(18, 52, 86)')
  await page.getByLabel('Inspector target scope').selectOption({ label: 'Rows' })
  await expect(page.getByLabel('Raw element selector')).toHaveValue('.fi-ta-row')
  await frame.locator('canvas').first().click({ position: { x: 30, y: 30 } })
  await expect(page.getByLabel('Raw element selector')).toHaveValue('.fi-wi-chart-canvas-ctn')
  await page.getByLabel('Raw background-color', { exact: true }).fill('#223344')
  await expect(frame.locator('.fi-wi-chart-canvas-ctn').first()).toHaveCSS('background-color', 'rgb(34, 51, 68)')
})

test('named color definitions update multiple live references and survive reload', async ({ page }) => {
  await page.locator('[data-user-token-name]').fill('brandaccent')
  await page.locator('[data-user-token-value]').fill('#123456')
  await page.locator('[data-user-token-create]').click()
  await page.getByLabel('page surface light named token', { exact: true }).selectOption('user.color.brandaccent')
  await page.getByLabel('sidebar surface light named token', { exact: true }).selectOption('user.color.brandaccent')
  const frame = page.frameLocator('iframe[title="Filament preview"]')
  await expect(frame.locator('body')).toHaveCSS('background-color', 'rgb(18, 52, 86)')
  await expect(frame.locator('.fi-sidebar')).toHaveCSS('background-color', 'rgb(18, 52, 86)')
  await page.getByLabel('Named color brandaccent').fill('#654321')
  await expect(frame.locator('body')).toHaveCSS('background-color', 'rgb(101, 67, 33)')
  await page.getByRole('button', { name: 'Save theme', exact: true }).click()
  await page.reload()
  await expect(page.frameLocator('iframe[title="Filament preview"]').locator('body')).toHaveCSS('background-color', 'rgb(101, 67, 33)')
})

test('a raw property can be linked using the active dark value and unlocked independently', async ({ page }) => {
  const frame = page.frameLocator('iframe[title="Filament preview"]')
  await page.getByRole('button', { name: 'Inspector', exact: true }).click()
  const visibleTarget = frame.locator('.fi-page').first()
  await expect(visibleTarget).toBeVisible()
  await visibleTarget.click({ position: { x: 24, y: 80 }, force: true })
  await page.getByLabel('Raw color', { exact: true }).fill('#123456')
  await page.getByRole('button', { name: 'Dark mode' }).click()
  await page.getByLabel('Raw color', { exact: true }).fill('#abcdef')
  page.once('dialog', (dialog) => dialog.accept())
  const colorLink = page.locator(`[data-mode-link-identity*='"kind":"raw"'][data-mode-link-identity*='"property":"color"']`)
  await colorLink.click()
  await page.getByRole('button', { name: 'Light mode' }).click()
  await expect(page.getByLabel('Raw color', { exact: true })).toHaveValue('#abcdef')
  await page.getByLabel('Raw color', { exact: true }).fill('#334455')
  await page.getByRole('button', { name: 'Dark mode' }).click()
  await expect(page.getByLabel('Raw color', { exact: true })).toHaveValue('#334455')
  await colorLink.click()
  await page.getByLabel('Raw color', { exact: true }).fill('#ffffff')
  await page.getByRole('button', { name: 'Light mode' }).click()
  await expect(page.getByLabel('Raw color', { exact: true })).toHaveValue('#334455')
})

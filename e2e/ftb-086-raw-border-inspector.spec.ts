import { expect, test } from '@playwright/test'

const baseUrl = process.env.COMPOSE_BASE_URL ?? 'http://127.0.0.1:4175'
test.skip(process.env.COMPOSE_E2E !== '1', 'Requires a running Compose stack')
test.use({ acceptDownloads: true })

async function selectSection(page: import('@playwright/test').Page) {
  const frame = page.frameLocator('iframe[title="Filament preview"]')
  await page.getByRole('button', { name: 'Inspector' }).click()
  await frame.locator('.fi-section:visible').first().dispatchEvent('click')
  const scope = page.getByLabel('Inspector target scope')
  const option = scope.locator('option').filter({ hasText: 'Surface: .fi-section' }).first()
  await scope.selectOption(await option.getAttribute('value') ?? '')
  const selector = await page.getByLabel('Raw element selector').inputValue()
  expect(selector).toContain('.fi-section')
  return frame.locator(`${selector}:visible`).first()
}

async function openExportMenu(page: import('@playwright/test').Page) {
  const summary = page.locator('summary[aria-label="Export actions"]')
  if (!(await summary.evaluate((element) => element.parentElement?.hasAttribute('open')))) await summary.click()
}

test.describe('FTB-086 raw physical border Inspector', () => {
  test.beforeEach(async ({ page }) => {
    await page.addInitScript(() => localStorage.removeItem('ftb-theme'))
    await page.goto(`${baseUrl}/`)
    await expect(page.getByTitle('Filament preview')).toBeVisible()
  })

  test('edits all sides, individual sides, zero and none, then survives reload and JSON export', async ({ page }) => {
    const target = await selectSection(page)
    const raw = page.getByRole('group', { name: 'Raw border edges' })
    await raw.getByRole('combobox', { name: 'Raw border property' }).selectOption('width')
    const allWidth = raw.getByRole('textbox', { name: 'Raw border width' })
    await allWidth.fill('0')
    await allWidth.dispatchEvent('change')
    await expect.poll(() => target.evaluate((element) => getComputedStyle(element).borderTopWidth)).toBe('0px')
    await raw.getByRole('combobox', { name: 'Raw border property' }).selectOption('style')
    const allStyle = raw.getByRole('combobox', { name: 'Raw border style' })
    await allStyle.selectOption('none')
    await allStyle.dispatchEvent('change')
    await expect.poll(() => target.evaluate((element) => getComputedStyle(element).borderBottomStyle)).toBe('none')
    await raw.getByRole('button', { name: 'top', exact: true }).click()
    await raw.getByRole('combobox', { name: 'Raw border property' }).selectOption('style')
    const topStyle = raw.getByRole('combobox', { name: 'Raw border style' })
    await topStyle.selectOption('solid')
    await topStyle.dispatchEvent('change')
    await raw.getByRole('combobox', { name: 'Raw border property' }).selectOption('width')
    const topWidth = raw.getByRole('textbox', { name: 'Raw border width' })
    await topWidth.fill('3px')
    await topWidth.dispatchEvent('change')
    await expect.poll(() => target.evaluate((element) => getComputedStyle(element).borderTopWidth)).toBe('3px')
    await page.getByRole('button', { name: 'Undo' }).click()
    await expect.poll(() => target.evaluate((element) => getComputedStyle(element).borderTopWidth)).toBe('0px')
    await page.getByRole('button', { name: 'Redo' }).click()
    await expect.poll(() => target.evaluate((element) => getComputedStyle(element).borderTopWidth)).toBe('3px')
    await page.waitForTimeout(500)
    await page.reload()
    await expect(page.getByTitle('Filament preview')).toBeVisible()
    await page.waitForTimeout(500)
    await selectSection(page)
    await expect(page.getByRole('group', { name: 'Raw border edges' }).getByRole('button', { name: 'top', exact: true })).toBeVisible()
    await openExportMenu(page)
    const [download] = await Promise.all([
      page.waitForEvent('download'),
      page.getByRole('button', { name: 'Download vanilla CSS' }).click(),
    ])
    const stream = await download.createReadStream()
    let css = ''
    for await (const chunk of stream ?? []) css += chunk.toString()
    expect(css).toContain('border-top-width: 3px;')
    expect(css).toContain('border-top-style: solid;')
    expect(css).toContain('border-right-style: none;')
    const clean = await page.context().newPage()
    await clean.goto(`${baseUrl}/demo/admin`)
    await clean.addStyleTag({ content: css })
    await expect.poll(() => clean.locator('.fi-section-has-header:visible').first().evaluate((element) => getComputedStyle(element).borderTopWidth)).toBe('3px')
    await clean.close()
    await openExportMenu(page)
    const [jsonDownload] = await Promise.all([
      page.waitForEvent('download'),
      page.getByRole('button', { name: 'Export theme JSON' }).click(),
    ])
    const jsonStream = await jsonDownload.createReadStream()
    let json = ''
    for await (const chunk of jsonStream ?? []) json += chunk.toString()
    expect(json).toContain('border-top-width')
    await page.locator('#raw-background-color').fill('#fef3c7')
    await expect.poll(() => target.evaluate((element) => getComputedStyle(element).backgroundColor)).toMatch(/254, 243, 199/)
    await page.getByRole('button', { name: 'Reset raw element override' }).click()
    await expect.poll(() => target.evaluate((element) => getComputedStyle(element).backgroundColor)).not.toMatch(/254, 243, 199/)
    await page.getByRole('button', { name: 'Undo' }).click()
    await expect.poll(() => target.evaluate((element) => getComputedStyle(element).backgroundColor)).toMatch(/254, 243, 199/)
    await page.getByRole('group', { name: 'Raw border edges' }).getByRole('button', { name: 'Reset raw border' }).click()
    await expect.poll(() => target.evaluate((element) => getComputedStyle(element).borderTopWidth)).toBe('0px')
  })

  test('keeps light and dark raw border values isolated and remains keyboard usable at narrow width', async ({ page }) => {
    const target = await selectSection(page)
    const raw = page.getByRole('group', { name: 'Raw border edges' })
    await raw.getByRole('combobox', { name: 'Raw border property' }).selectOption('color')
    await raw.getByRole('textbox', { name: 'Raw border color' }).fill('#123456')
    await raw.getByRole('textbox', { name: 'Raw border color' }).dispatchEvent('change')
    await page.getByRole('button', { name: 'Dark mode' }).click()
    await expect(page.getByRole('button', { name: 'Dark mode' })).toHaveAttribute('aria-pressed', 'true')
    await raw.getByRole('combobox', { name: 'Raw border property' }).selectOption('color')
    await raw.getByRole('textbox', { name: 'Raw border color' }).fill('#abcdef')
    await raw.getByRole('textbox', { name: 'Raw border color' }).dispatchEvent('change')
    await page.getByRole('button', { name: 'Light mode' }).click()
    await expect(raw.getByRole('textbox', { name: 'Raw border color' })).toHaveValue('#123456')
    await raw.getByRole('textbox', { name: 'Raw border color' }).fill('var(--color-primary-500)')
    await raw.getByRole('textbox', { name: 'Raw border color' }).dispatchEvent('change')
    await page.getByRole('button', { name: 'Dark mode' }).click()
    await raw.getByRole('textbox', { name: 'Raw border color' }).fill('var(--color-danger-500)')
    await raw.getByRole('textbox', { name: 'Raw border color' }).dispatchEvent('change')
    await page.getByRole('button', { name: 'Light mode' }).click()
    await openExportMenu(page)
    const [download] = await Promise.all([
      page.waitForEvent('download'),
      page.getByRole('button', { name: 'Download vanilla CSS' }).click(),
    ])
    const stream = await download.createReadStream()
    let css = ''
    for await (const chunk of stream ?? []) css += chunk.toString()
    expect(css).toContain(':where(html:not(.dark))')
    expect(css).toContain(':where(html.dark)')
    expect(css).toContain('border-top-color: var(--color-primary-500);')
    expect(css).toContain('border-top-color: var(--color-danger-500);')
    const clean = await page.context().newPage()
    await clean.goto(`${baseUrl}/demo/admin`)
    await clean.addStyleTag({ content: css })
    const lightBorder = await clean.locator('.fi-section-has-header:visible').first().evaluate((element) => getComputedStyle(element).borderTopColor)
    await clean.evaluate(() => document.documentElement.classList.add('dark'))
    const darkBorder = await clean.locator('.fi-section-has-header:visible').first().evaluate((element) => getComputedStyle(element).borderTopColor)
    expect(lightBorder).not.toBe(darkBorder)
    await clean.close()
    await page.setViewportSize({ width: 390, height: 844 })
    await expect(page.locator('[data-advanced-inspector]')).toBeVisible()
    await raw.getByRole('button', { name: 'Reset raw border' }).focus()
    await expect(raw.getByRole('button', { name: 'Reset raw border' })).toBeFocused()
    await expect(target).toBeVisible()
  })

  test('uses ring-backed raw projection while preserving native focus ring behavior', async ({ page }) => {
    await selectSection(page)
    await page.getByLabel('Raw element selector').fill('.fi-input-wrp')
    const raw = page.getByRole('group', { name: 'Raw border edges' })
    await raw.getByRole('combobox', { name: 'Raw border property' }).selectOption('style')
    const style = raw.getByRole('combobox', { name: 'Raw border style' })
    await style.selectOption('solid')
    await style.dispatchEvent('change')
    await raw.getByRole('combobox', { name: 'Raw border property' }).selectOption('width')
    const width = raw.getByRole('textbox', { name: 'Raw border width' })
    await width.fill('2px')
    await width.dispatchEvent('change')
    const frame = page.frameLocator('iframe[title="Filament preview"]')
    const ringTarget = frame.locator('.fi-input-wrp:visible').first()
    await expect(ringTarget).toHaveCount(1)
    await expect.poll(() => ringTarget.evaluate((element) => getComputedStyle(element).borderTopWidth)).toBe('2px')
    const projection = await frame.locator('style#ftb-managed-theme').textContent()
    expect(projection).toContain('.fi-input-wrp:not(:focus):not(:focus-within):not(:focus-visible)')
    expect(projection).toContain('--tw-ring-shadow: 0 0 #0000')
    const focusTarget = ringTarget.locator('input:visible, button:visible').first()
    await expect(focusTarget).toHaveCount(1)
    await focusTarget.focus()
    await expect.poll(() => focusTarget.evaluate((element) => getComputedStyle(element).boxShadow)).not.toBe('none')
  })

  test('applies a raw border edge to a supported Inspector state variant', async ({ page }) => {
    const target = await selectSection(page)
    await page.getByRole('button', { name: 'Hover', exact: true }).click()
    await expect(page.getByLabel('Raw element selector')).toHaveValue(/:hover$/)
    const raw = page.getByRole('group', { name: 'Raw border edges' })
    await raw.getByRole('combobox', { name: 'Raw border property' }).selectOption('style')
    const style = raw.getByRole('combobox', { name: 'Raw border style' })
    await style.selectOption('solid')
    await style.dispatchEvent('change')
    await raw.getByRole('combobox', { name: 'Raw border property' }).selectOption('width')
    const width = raw.getByRole('textbox', { name: 'Raw border width' })
    await width.fill('4px')
    await width.dispatchEvent('change')
    await target.hover()
    await expect.poll(() => target.evaluate((element) => getComputedStyle(element).borderTopWidth)).toBe('4px')
  })

  test('links a physical raw edge value across modes', async ({ page }) => {
    await selectSection(page)
    const width = page.locator('#raw-border-top-width')
    await width.fill('2')
    await width.dispatchEvent('input')
    const link = page.locator('[data-mode-link-identity*="border-top-width"]').first()
    await expect(link).toBeVisible()
    await link.click()
    await page.getByRole('button', { name: 'Dark mode' }).click()
    await expect(page.locator('#raw-border-top-width')).toHaveValue('2')
    await expect(page.locator('[data-mode-link-identity*="border-top-width"]').first()).toHaveAttribute('aria-pressed', 'true')
  })
})

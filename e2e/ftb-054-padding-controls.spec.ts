import { expect, test, type Page } from '@playwright/test'

async function openAuthenticatedBuilder(page: Page): Promise<void> {
  await page.goto('/demo/admin/login')
  await page.locator('#form\\.email').fill('user')
  await page.locator('#form\\.password').fill('password')
  await page.locator('#form').evaluate((form) => (form as HTMLFormElement).requestSubmit())
  await expect(page).toHaveURL(/\/demo\/admin$/)
  await page.goto('/')
}

test('edits hierarchical padding with keyboard access and reset', async ({ page }) => {
  await openAuthenticatedBuilder(page)
  await page.getByRole('tab', { name: 'Components' }).click()
  const panel = page.getByRole('region', { name: 'Hierarchical padding controls' })
  await expect(panel).toBeVisible()
  const row = panel.locator('[data-padding-target="forms.input"]').filter({ has: page.getByRole('heading', { name: /Component/ }) })
  await expect(row).toContainText('forms.input')
  await row.getByRole('button', { name: /Edit separate/ }).focus()
  await page.keyboard.press('Enter')
  await row.getByRole('spinbutton', { name: 'forms.input · Component top padding' }).fill('8')
  await row.getByRole('spinbutton', { name: 'forms.input · Component top padding' }).press('Tab')
  await expect(row).toContainText('8px')
  await row.getByRole('button', { name: 'Reset Component forms.input padding' }).click()
  await expect(row).toContainText('Native fallback')
})

test('keeps hierarchy usable at narrow zoom and preserves child overrides', async ({ page }) => {
  await page.setViewportSize({ width: 640, height: 900 })
  await openAuthenticatedBuilder(page)
  await page.getByRole('tab', { name: 'Components' }).click()
  await page.evaluate(() => { document.documentElement.style.zoom = '0.8' })
  const panel = page.getByRole('region', { name: 'Hierarchical padding controls' })
  await page.locator('iframe[title="Filament preview"]').evaluate((iframe, url) => { (iframe as HTMLIFrameElement).src = url as string }, `${new URL(page.url()).origin}/demo/admin/forms-showcase`)
  await expect.poll(() => page.frames().find((candidate) => /\/demo\/admin\/forms-showcase/.test(candidate.url()))?.url() ?? '').toContain('/demo/admin/forms-showcase')
  const global = panel.locator('[data-padding-context="forms.input-global"]')
  const section = panel.locator('[data-padding-context="forms.input-section"]')
  const component = panel.locator('[data-padding-context="forms.input-component"]')
  const frame = page.frameLocator('iframe[title="Filament preview"]')
  await expect(global).toBeVisible(); await expect(section).toBeVisible(); await expect(component).toBeVisible()
  await section.getByRole('spinbutton', { name: 'forms.input · Section · forms linked padding' }).fill('54')
  await expect(section.getByLabel('forms.input · Section · forms linked padding unit')).toHaveValue('px')
  await expect(frame.locator('.fi-fo-text-input .fi-input').first()).toHaveCSS('padding-top', '54px')
  await section.getByRole('button', { name: 'Reset Section · forms forms.input padding' }).click()
  await global.getByRole('spinbutton', { name: 'forms.input · Global linked padding' }).fill('10')
  await expect(component).toContainText('Source: global')
  await expect(frame.locator('.fi-fo-text-input .fi-input').first()).toHaveCSS('padding-top', '10px')
  await expect(frame.locator('.fi-fo-text-input .fi-input').first()).toHaveCSS('padding-right', '10px')
  await expect(frame.locator('.fi-fo-text-input .fi-input').first()).toHaveCSS('padding-bottom', '10px')
  await expect(frame.locator('.fi-fo-text-input .fi-input').first()).toHaveCSS('padding-left', '10px')
  await component.getByRole('button', { name: /Edit separate/ }).click()
  await component.getByRole('spinbutton', { name: 'forms.input · Component top padding' }).fill('14'); await component.getByRole('spinbutton', { name: 'forms.input · Component top padding' }).press('Tab')
  await section.getByRole('spinbutton', { name: 'forms.input · Section · forms linked padding' }).fill('12')
  await expect(component).toContainText('14px'); await expect(component).toContainText('Source: component')
  await component.getByRole('button', { name: 'Reset Component forms.input padding' }).click()
  await expect(component).toContainText('Source: section')
  await section.getByRole('button', { name: 'Reset Section · forms forms.input padding' }).click()
  await expect(component).toContainText('Source: global')
  await global.getByRole('button', { name: 'Reset Global forms.input padding' }).click()
  await expect(component).toContainText('Native fallback')
  await expect(frame.locator('.fi-fo-text-input .fi-input').first()).toHaveCSS('padding-top', '6px')
  await expect(panel.locator('[data-padding-target="forms.input"]')).toHaveCount(3)
  await expect(panel.locator('[data-padding-target="tables.container"]')).toHaveCount(1)
})

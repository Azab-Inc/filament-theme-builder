import { expect, test } from '@playwright/test'

import { builderBaseUrl } from './urls'

const viewports = [
  { name: 'desktop', width: 1280, height: 900 },
  { name: 'intermediate', width: 900, height: 900 },
  { name: 'narrow', width: 640, height: 900 },
] as const

test.describe('FTB-065 editor and preview divider', () => {
  for (const viewport of viewports) {
    test(`resizes both panes at ${viewport.name} width`, async ({ page }) => {
      await page.setViewportSize(viewport)
      await page.goto(builderBaseUrl)
      const divider = page.getByRole('separator', { name: 'Resize editor and preview' })
      await expect(divider).toBeVisible()
      await expect(divider).toHaveAttribute('aria-orientation', 'vertical')
      await expect(divider).toHaveAttribute('aria-valuemin', '280')
      const before = await page.locator('[data-editor-panel]').boundingBox()
      const beforePreview = await page.locator('[data-editor-iframe]').boundingBox()
      expect(before).not.toBeNull()
      expect(beforePreview).not.toBeNull()
      expect(before!.width).toBeGreaterThanOrEqual(280)
      expect(beforePreview!.width).toBeGreaterThanOrEqual(280)
      for (const navigation of ['Sidebar', 'Top navigation']) {
        await page.getByRole('radio', { name: navigation }).check()
        const handle = await divider.boundingBox()
        expect(handle).not.toBeNull()
        await page.mouse.move(handle!.x + 2, handle!.y + 100)
        await page.mouse.down()
        await page.mouse.move(handle!.x - 80, handle!.y + 100)
        await page.mouse.up()
        const afterLeft = await page.locator('[data-editor-panel]').boundingBox()
        const afterLeftPreview = await page.locator('[data-editor-iframe]').boundingBox()
        expect(afterLeft!.width).toBeLessThan(before!.width)
        expect(afterLeftPreview!.width).toBeGreaterThan(beforePreview!.width)
        expect(afterLeft!.width).toBeGreaterThanOrEqual(280)
        expect(afterLeftPreview!.width).toBeGreaterThanOrEqual(280)
        await page.mouse.move((await divider.boundingBox())!.x + 2, handle!.y + 100)
        await page.mouse.down()
        await page.mouse.move((await divider.boundingBox())!.x + 120, handle!.y + 100)
        await page.mouse.up()
        const afterRight = await page.locator('[data-editor-panel]').boundingBox()
        const afterRightPreview = await page.locator('[data-editor-iframe]').boundingBox()
        expect(afterRight!.width).toBeGreaterThan(afterLeft!.width)
        expect(afterRightPreview!.width).toBeLessThan(afterLeftPreview!.width)
        expect(afterRightPreview!.width).toBeGreaterThanOrEqual(280)
        expect(await page.frameLocator('[data-editor-iframe]').locator('html').evaluate((html) => html.clientWidth)).toBeGreaterThan(0)
      }
      if (viewport.width >= 900) {
        await page.setViewportSize({ width: viewport.width - 100, height: viewport.height })
        await expect(divider).toBeVisible()
        const resizedMaximum = Number(await divider.getAttribute('aria-valuemax'))
        const resizedPanel = await page.locator('[data-editor-panel]').boundingBox()
        const resizedPreview = await page.locator('[data-editor-iframe]').boundingBox()
        expect(Number(await divider.getAttribute('aria-valuenow'))).toBeLessThanOrEqual(resizedMaximum)
        expect(resizedPanel!.width).toBeGreaterThanOrEqual(280)
        expect(resizedPreview!.width).toBeGreaterThanOrEqual(280)
      }
    })
  }

  test('supports keyboard resizing and keeps state through both navigation layouts', async ({ page }) => {
    await page.goto(builderBaseUrl)
    await page.locator('[data-color-field="toolbar-color-segments"] input.color-field__text').fill('#0f766e')
    await page.getByRole('button', { name: 'Dark mode' }).click()
    await page.locator('[data-color-field="toolbar-color-segments"] input.color-field__text').fill('#dc2626')
    await page.getByRole('button', { name: 'Light mode' }).click()
    await expect(page.locator('[data-color-field="toolbar-color-segments"] input.color-field__text')).toHaveValue('#0f766e')
    await page.getByRole('button', { name: 'Dark mode' }).click()
    await expect(page.locator('[data-color-field="toolbar-color-segments"] input.color-field__text')).toHaveValue('#dc2626')
    await page.getByRole('button', { name: 'Undo' }).click()
    await expect(page.locator('[data-color-field="toolbar-color-segments"] input.color-field__text')).toHaveValue('#0f766e')
    await page.getByRole('button', { name: 'Redo' }).click()
    await expect(page.locator('[data-color-field="toolbar-color-segments"] input.color-field__text')).toHaveValue('#dc2626')
    const divider = page.getByRole('separator', { name: 'Resize editor and preview' })
    await divider.focus()
    await expect(divider).toHaveAttribute('aria-valuemin', '280')
    await expect(divider).toHaveAttribute('aria-valuemax', /\d+/)
    const initialSrc = await page.locator('[data-editor-iframe]').getAttribute('src')
    await page.getByRole('radio', { name: 'Top navigation' }).check()
    await page.getByRole('tab', { name: 'Components' }).click()
    await divider.press('Home')
    await expect(divider).toHaveAttribute('aria-valuenow', '280')
    await expect(divider).toHaveAttribute('aria-valuetext', '280 pixels editor width')
    await divider.press('End')
    const maximum = Number(await divider.getAttribute('aria-valuemax'))
    await expect(divider).toHaveAttribute('aria-valuenow', String(maximum))
    await expect(divider).toHaveAttribute('aria-valuetext', `${maximum} pixels editor width`)
    await divider.press('ArrowRight')
    await expect(divider).toBeFocused()
    await page.getByRole('radio', { name: 'Sidebar' }).check()
    await expect(page.getByRole('tab', { name: 'Components' })).toBeVisible()
    await expect(page.locator('[data-editor-iframe]')).toHaveAttribute('src', initialSrc!)
    await expect(page.locator('[data-color-field="toolbar-color-segments"] input.color-field__text')).toHaveValue('#dc2626')
    await expect(page.getByRole('button', { name: 'Dark mode' })).toHaveAttribute('aria-pressed', 'true')
    await expect(page.getByRole('button', { name: 'Undo' })).toBeEnabled()
    await page.getByRole('button', { name: 'Undo' }).click()
    await expect(page.locator('[data-color-field="toolbar-color-segments"] input.color-field__text')).toHaveValue('#0f766e')
    await page.getByRole('button', { name: 'Redo' }).click()
    await expect(page.locator('[data-color-field="toolbar-color-segments"] input.color-field__text')).toHaveValue('#dc2626')
    await page.getByRole('button', { name: 'Inspector' }).click()
    await page.frameLocator('[data-editor-iframe]').locator('.fi-section:visible').first().click()
    await expect(page.getByRole('tab', { name: 'Inspector' })).toBeVisible()
  })

  test('captures real touch movement across the iframe without losing either pane', async ({ browser }) => {
    const context = await browser.newContext({ hasTouch: true, viewport: { width: 1280, height: 900 } })
    const page = await context.newPage()
    await page.goto(builderBaseUrl)
    const divider = page.getByRole('separator', { name: 'Resize editor and preview' })
    const box = await divider.boundingBox()
    const before = await page.locator('[data-editor-panel]').boundingBox()
    const preview = await page.locator('[data-editor-iframe]').boundingBox()
    expect(box).not.toBeNull()
    expect(before).not.toBeNull()
    expect(preview).not.toBeNull()
    const client = await context.newCDPSession(page)
    const startX = box!.x + box!.width / 2
    const y = box!.y + box!.height / 2
    const targetX = preview!.x + Math.min(120, preview!.width / 2)
    await client.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: startX, y }] })
    await client.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: targetX, y }] })
    await client.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
    const after = await page.locator('[data-editor-panel]').boundingBox()
    const afterPreview = await page.locator('[data-editor-iframe]').boundingBox()
    expect(after!.width).toBeGreaterThan(before!.width)
    expect(afterPreview!.width).toBeLessThan(preview!.width)
    expect(afterPreview!.x).toBeGreaterThanOrEqual(after!.x + after!.width)
    await expect(page.locator('[data-editor-iframe]')).toBeVisible()
    await expect(page.getByRole('heading', { name: 'Filament Theme Builder' })).toBeVisible()
    await context.close()
  })
})

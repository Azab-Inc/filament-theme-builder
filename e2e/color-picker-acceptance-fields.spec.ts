import { expect, test } from '@playwright/test'
import { baseUrl, chooseToken, openChooser, readCanonical, setPreviewRoute } from './color-picker-acceptance.helpers'

test.describe('color picker field acceptance', () => {
  test.skip(process.env.COMPOSE_E2E !== '1', 'requires the canonical Compose stack')

  test('updates toolbar primary and a mapped palette base without iframe reload', async ({ page }) => {
    const navigations: string[] = []
    page.on('request', (request) => { if (request.isNavigationRequest()) navigations.push(request.url()) })
    await page.goto(baseUrl); const frame = await setPreviewRoute(page, '/demo/admin/showcase')
    const toolbarBefore = await readCanonical(page)
    await openChooser(page, 'Primary color'); await chooseToken(page)
    await expect(page.locator('#toolbar-primary-color')).toHaveValue('#101828')
    await expect.poll(async () => (await readCanonical(page)).colors.primary).toBe('#101828')
    expect((await readCanonical(page)).colors.primary).not.toBe(toolbarBefore.colors.primary)
    await expect.poll(() => frame.evaluate(() => getComputedStyle(document.documentElement).getPropertyValue('--ftb-primary').trim())).toBe('#101828')
    navigations.length = 0
    const baseBefore = await readCanonical(page)
    await page.getByRole('button', { name: 'Primary', exact: true }).click()
    await openChooser(page, 'primary palette base'); await chooseToken(page, 'red 500 #fb2c36')
    await expect(page.locator('#primary-palette-base')).toHaveValue('#fb2c36')
    await expect.poll(async () => (await readCanonical(page)).foundations.palettes.primary.base).toBe('#fb2c36')
    await page.getByRole('button', { name: 'Undo' }).click()
    await expect(page.locator('#primary-palette-base')).toHaveValue(baseBefore.foundations.palettes.primary.base)
    await expect.poll(async () => (await readCanonical(page)).foundations.palettes.primary.base).toBe(baseBefore.foundations.palettes.primary.base)
    await page.getByRole('button', { name: 'Redo' }).click()
    await expect(page.locator('#primary-palette-base')).toHaveValue('#fb2c36')
    await expect.poll(async () => (await readCanonical(page)).foundations.palettes.primary.base).toBe('#fb2c36')
    expect(navigations).toEqual([])
  })

  test('selects a shade, undoes/redoes it, and reset restores the generated ramp', async ({ page }) => {
    await page.goto(baseUrl); const frame = await setPreviewRoute(page, '/demo/admin/showcase')
    await page.getByRole('button', { name: 'Primary', exact: true }).click()
    const input = page.locator('#primary-shade-900')
    await expect(input).toHaveValue('')
    await expect(page.locator('[data-palette-status="primary-shade-900"]')).toContainText('generated')
    const generated = await frame.evaluate(() => getComputedStyle(document.documentElement).getPropertyValue('--primary-900').trim())
    await openChooser(page, 'primary shade 900 override')
    await chooseToken(page)
    await expect(input).toHaveValue('#101828')
    await expect.poll(async () => (await readCanonical(page)).foundations.palettes.primary.overrides[900]).toBe('#101828')
    await expect.poll(() => frame.evaluate(() => getComputedStyle(document.documentElement).getPropertyValue('--primary-900').trim())).toBe('#101828')
    await page.getByRole('button', { name: 'Undo' }).click(); await expect(input).toHaveValue('')
    await expect.poll(async () => (await readCanonical(page)).foundations.palettes.primary.overrides[900] ?? null).toBe(null)
    await page.getByRole('button', { name: 'Redo' }).click(); await expect(input).toHaveValue('#101828')
    await page.getByRole('button', { name: 'Reset primary shade 900' }).click()
    await expect(input).toHaveValue(''); await expect(page.locator('[data-palette-status="primary-shade-900"]')).toContainText('generated')
    await expect.poll(() => frame.evaluate(() => getComputedStyle(document.documentElement).getPropertyValue('--primary-900').trim())).toBe(generated)
  })

  test('isolates light and dark surface, border, and text fields', async ({ page }) => {
    await page.goto(baseUrl); const frame = await setPreviewRoute(page, '/demo/admin/showcase')
    await openChooser(page, 'page surface light'); await chooseToken(page, 'red 500 #fb2c36')
    await expect(page.locator('#page-surface')).toHaveValue('#fb2c36')
    await page.getByRole('button', { name: 'Dark mode' }).click()
    await openChooser(page, 'page surface dark'); await chooseToken(page)
    await openChooser(page, 'border default dark'); await chooseToken(page, 'red 500 #fb2c36')
    await openChooser(page, 'text primary dark'); await chooseToken(page)
    await expect(page.locator('#text-primary-dark')).toHaveValue('#101828')
    await expect.poll(async () => (await readCanonical(page)).foundations.surfaces.page.light).toBe('#fb2c36')
    await expect.poll(async () => (await readCanonical(page)).foundations.surfaces.page.dark).toBe('#101828')
    await expect.poll(async () => (await readCanonical(page)).foundations.borders.default.dark).toBe('#fb2c36')
    await expect.poll(async () => (await readCanonical(page)).foundations.text.primary.dark).toBe('#101828')
    await expect.poll(() => frame.evaluate(() => getComputedStyle(document.documentElement).getPropertyValue('--ftb-foundation-border-default').trim())).toBe('#fb2c36')
    await expect.poll(() => frame.evaluate(() => getComputedStyle(document.documentElement).getPropertyValue('--ftb-foundation-text-primary').trim())).toBe('#101828')
    await page.getByRole('button', { name: 'Light mode' }).click()
    await expect(page.locator('#page-surface')).toHaveValue('#fb2c36')
    await expect(page.locator('#border-default-light')).not.toHaveValue('#fb2c36')
    await expect.poll(async () => (await readCanonical(page)).foundations.borders.default.light).not.toBe('#fb2c36')
    await expect.poll(() => frame.evaluate(() => getComputedStyle(document.documentElement).getPropertyValue('--ftb-foundation-border-default').trim())).not.toBe('#fb2c36')
  })
})

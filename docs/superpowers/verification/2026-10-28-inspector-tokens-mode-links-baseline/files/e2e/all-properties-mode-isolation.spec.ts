import { expect, test } from '@playwright/test'
import { authenticate, readCanonical, setPreviewRoute } from './color-picker-acceptance.helpers'

const baseUrl = process.env.COMPOSE_BASE_URL ?? 'http://127.0.0.1:4175'
test.skip(process.env.COMPOSE_E2E !== '1', 'Requires the canonical Compose stack')

test('mode-specific theme values survive reset/history/reload and exported CSS applies to light and dark roots', async ({ page }) => {
  await authenticate(page)
  await page.evaluate(() => {
    for (const key of Object.keys(localStorage)) if (key.startsWith('ftb-theme')) localStorage.removeItem(key)
  })
  await page.goto(baseUrl)
  const frame = page.frameLocator('iframe[title="Filament preview"]')

  await page.locator('[data-palette-header="primary"]').click()
  await page.locator('#primary-palette-base').fill('#123456')
  await page.locator('#primary-shade-500').fill('#234567')
  await page.getByRole('button', { name: 'Dark mode' }).click()
  await page.locator('#primary-palette-base').fill('#654321')
  await page.locator('#primary-shade-500').fill('#765432')
  await expect.poll(async () => (await readCanonical(page)).foundations.palettes.primary.dark?.base).toBe('#654321')
  await expect.poll(() => frame.locator('html').evaluate((root) => getComputedStyle(root).getPropertyValue('--ftb-primary').trim())).toBe('#654321')
  await expect.poll(() => frame.locator('html').evaluate((root) => getComputedStyle(root).getPropertyValue('--primary-500').trim())).toBe('#765432')
  await page.getByRole('button', { name: 'Light mode' }).click()
  await expect.poll(() => frame.locator('html').evaluate((root) => getComputedStyle(root).getPropertyValue('--ftb-primary').trim())).toBe('#123456')

  await page.getByRole('button', { name: 'Inspector' }).click()
  const selected = frame.locator('.fi-sidebar-item.fi-active .fi-sidebar-item-label').first()
  await selected.evaluate((node) => (node as HTMLElement).click())
  await page.getByRole('button', { name: 'Selected' }).click()
  await page.getByLabel('Raw color', { exact: true }).fill('#119944')
  await page.getByRole('button', { name: 'Dark mode' }).click()
  await page.getByLabel('Raw color', { exact: true }).fill('#994411')
  await expect.poll(async () => (await readCanonical(page)).rawOverrides.some((item: { darkProperties?: Record<string, string> }) => item.darkProperties?.color === '#994411')).toBe(true)
  await expect.poll(() => selected.evaluate((node) => getComputedStyle(node).color)).toBe('rgb(153, 68, 17)')
  await page.getByRole('button', { name: 'Reset raw color' }).click()
  await page.getByRole('button', { name: 'Undo' }).click()
  await expect.poll(() => selected.evaluate((node) => getComputedStyle(node).color)).toBe('rgb(153, 68, 17)')
  await page.getByRole('button', { name: 'Light mode' }).click()
  await expect.poll(() => selected.evaluate((node) => getComputedStyle(node).color)).toBe('rgb(17, 153, 68)')
  await expect.poll(async () => (await readCanonical(page)).foundations.palettes.primary.base).toBe('#123456')
  await page.reload()

  await setPreviewRoute(page, '/demo/admin/forms-showcase')
  await page.getByRole('tab', { name: 'Components' }).click()
  await page.locator('#product-name-global-background').fill('#cc2233')
  await page.getByRole('button', { name: 'Dark mode' }).click()
  await page.locator('#product-name-global-background').fill('#2233cc')
  const productInput = page.frameLocator('iframe[title="Filament preview"]').locator('.fi-fo-text-input .fi-input').first()
  await expect.poll(() => productInput.evaluate((node) => getComputedStyle(node).backgroundColor)).toBe('rgb(34, 51, 204)')
  await page.getByRole('button', { name: 'Light mode' }).click()
  await expect.poll(() => productInput.evaluate((node) => getComputedStyle(node).backgroundColor)).toBe('rgb(204, 34, 51)')
  await page.getByRole('tab', { name: 'Foundations' }).click()
  await page.getByLabel('Text primary light', { exact: true }).fill('#102030')
  await page.getByLabel('page surface light', { exact: true }).fill('#eeddcc')
  await page.getByRole('button', { name: 'Dark mode' }).click()
  await page.getByLabel('Text primary dark', { exact: true }).fill('#e0d0c0')
  await page.getByLabel('page surface dark', { exact: true }).fill('#302010')

  const exportMenu = page.locator('summary[aria-label="Export actions"]')
  await exportMenu.click()
  const [download] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: 'Download vanilla CSS' }).click()])
  const stream = await download.createReadStream()
  let css = ''
  for await (const chunk of stream ?? []) css += chunk.toString()

  const isolated = await page.context().newPage()
  await isolated.setContent('<html><body><main class="fi-main"><nav class="fi-sidebar"><a class="fi-sidebar-item fi-active"><span class="fi-sidebar-item-label">Active</span></a></nav><section class="fi-fo-text-input"><input class="fi-input"></section></main></body></html>')
  await isolated.addStyleTag({ content: css })
  const root = isolated.locator('html')
  const exportedLabel = isolated.locator('.fi-sidebar-item-label')
  await expect.poll(() => root.evaluate((node) => getComputedStyle(node).getPropertyValue('--ftb-primary').trim())).toBe('#123456')
  await expect.poll(() => root.evaluate((node) => getComputedStyle(node).getPropertyValue('--primary-500').trim())).toBe('#234567')
  await expect(exportedLabel).toHaveCSS('color', 'rgb(17, 153, 68)')
  await expect(isolated.locator('body')).toHaveCSS('background-color', 'rgb(238, 221, 204)')
  await expect(isolated.locator('body')).toHaveCSS('color', 'rgb(16, 32, 48)')
  await root.evaluate((node) => node.classList.add('dark'))
  await expect.poll(() => root.evaluate((node) => getComputedStyle(node).getPropertyValue('--ftb-primary').trim())).toBe('#654321')
  await expect.poll(() => root.evaluate((node) => getComputedStyle(node).getPropertyValue('--primary-500').trim())).toBe('#765432')
  await expect.poll(() => isolated.locator('.fi-input').evaluate((node) => getComputedStyle(node).backgroundColor)).toBe('rgb(34, 51, 204)')
  await expect(exportedLabel).toHaveCSS('color', 'rgb(153, 68, 17)')
  await expect(isolated.locator('body')).toHaveCSS('background-color', 'rgb(48, 32, 16)')
  await expect(isolated.locator('body')).toHaveCSS('color', 'rgb(224, 208, 192)')
  await root.evaluate((node) => node.classList.remove('dark'))
  await expect(isolated.locator('.fi-input')).toHaveCSS('background-color', 'rgb(204, 34, 51)')
  await expect(isolated.locator('body')).toHaveCSS('background-color', 'rgb(238, 221, 204)')
  await isolated.close()
})
